package agents

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const markerPrefix = "<!-- skillcloud:group:"

// BeginMarker returns the start marker for a managed group block.
func BeginMarker(groupID string) string {
	return markerPrefix + groupID + ":begin -->"
}

// EndMarker returns the end marker for a managed group block.
func EndMarker(groupID string) string {
	return markerPrefix + groupID + ":end -->"
}

// Render builds the managed block for a group.
func Render(groupID string, title string, content string) string {
	title = strings.TrimSpace(title)
	if title == "" {
		title = groupID
	}
	body := stripLeadingHeading(strings.TrimSpace(content))

	var b strings.Builder
	b.WriteString(BeginMarker(groupID))
	b.WriteString("\n")
	b.WriteString("<!-- Generated by skillcloud from the group's AGENTS.md. Do not edit this block directly. -->\n\n")
	fmt.Fprintf(&b, "## Skill group: %s\n\n", title)
	if body != "" {
		b.WriteString(body)
		if !strings.HasSuffix(body, "\n") {
			b.WriteString("\n")
		}
	}
	b.WriteString(EndMarker(groupID))
	return b.String()
}

// Upsert writes or replaces a group's managed block in path.
func Upsert(path string, groupID string, title string, content string) error {
	original, mode, err := readOptionalFile(path)
	if err != nil {
		return err
	}
	crlf := strings.Contains(original, "\r\n")
	normalized := strings.ReplaceAll(original, "\r\n", "\n")
	lines := strings.Split(normalized, "\n")

	begin, end, err := findBlock(lines, groupID)
	if err != nil {
		return err
	}
	blockLines := strings.Split(Render(groupID, title, content), "\n")
	if begin >= 0 {
		replaced := make([]string, 0, len(lines)-(end-begin+1)+len(blockLines))
		replaced = append(replaced, lines[:begin]...)
		replaced = append(replaced, blockLines...)
		replaced = append(replaced, lines[end+1:]...)
		lines = replaced
	} else {
		for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
			lines = lines[:len(lines)-1]
		}
		if len(lines) > 0 {
			lines = append(lines, "")
		}
		lines = append(lines, blockLines...)
		lines = append(lines, "")
	}

	out := strings.Join(lines, "\n")
	if crlf {
		out = strings.ReplaceAll(out, "\n", "\r\n")
	}
	return writeAtomic(path, []byte(out), mode)
}

// Remove deletes a group's managed block from path. Missing files and blocks are no-ops.
func Remove(path string, groupID string) error {
	original, mode, err := readOptionalFile(path)
	if err != nil {
		return err
	}
	if original == "" {
		return nil
	}
	crlf := strings.Contains(original, "\r\n")
	normalized := strings.ReplaceAll(original, "\r\n", "\n")
	lines := strings.Split(normalized, "\n")

	begin, end, err := findBlock(lines, groupID)
	if err != nil {
		return err
	}
	if begin < 0 {
		return nil
	}
	lines = append(lines[:begin], lines[end+1:]...)
	// Collapse a blank-line seam left by removing the block.
	for begin > 0 && begin < len(lines) && strings.TrimSpace(lines[begin]) == "" && strings.TrimSpace(lines[begin-1]) == "" {
		lines = append(lines[:begin], lines[begin+1:]...)
	}

	out := strings.Join(lines, "\n")
	if crlf {
		out = strings.ReplaceAll(out, "\n", "\r\n")
	}
	return writeAtomic(path, []byte(out), mode)
}

// List returns the group IDs with managed blocks in path.
func List(path string) ([]string, error) {
	original, _, err := readOptionalFile(path)
	if err != nil || original == "" {
		return nil, err
	}
	normalized := strings.ReplaceAll(original, "\r\n", "\n")
	var ids []string
	for _, line := range strings.Split(normalized, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, markerPrefix) && strings.HasSuffix(trimmed, ":begin -->") {
			id := strings.TrimSuffix(strings.TrimPrefix(trimmed, markerPrefix), ":begin -->")
			if id != "" {
				ids = append(ids, id)
			}
		}
	}
	return ids, nil
}

func findBlock(lines []string, groupID string) (int, int, error) {
	beginMarker := BeginMarker(groupID)
	endMarker := EndMarker(groupID)
	begin := -1
	for i, line := range lines {
		if strings.TrimSpace(line) != beginMarker {
			continue
		}
		if begin >= 0 {
			return -1, -1, fmt.Errorf("multiple managed blocks for group %q", groupID)
		}
		begin = i
	}
	if begin < 0 {
		return -1, -1, nil
	}
	for i := begin + 1; i < len(lines); i++ {
		if strings.TrimSpace(lines[i]) == endMarker {
			return begin, i, nil
		}
	}
	return -1, -1, fmt.Errorf("unterminated managed block for group %q", groupID)
}

func stripLeadingHeading(content string) string {
	lines := strings.Split(content, "\n")
	i := 0
	for i < len(lines) && strings.TrimSpace(lines[i]) == "" {
		i++
	}
	if i < len(lines) && strings.HasPrefix(strings.TrimSpace(lines[i]), "# ") {
		i++
		for i < len(lines) && strings.TrimSpace(lines[i]) == "" {
			i++
		}
		return strings.Join(lines[i:], "\n")
	}
	return content
}

func readOptionalFile(path string) (string, fs.FileMode, error) {
	mode := fs.FileMode(0o644)
	info, err := os.Stat(path)
	if err == nil {
		mode = info.Mode().Perm()
	} else if !os.IsNotExist(err) {
		return "", mode, err
	}
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return "", mode, nil
	}
	if err != nil {
		return "", mode, err
	}
	return string(data), mode, nil
}

func writeAtomic(path string, data []byte, mode fs.FileMode) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".AGENTS-*.tmp")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if err := tmp.Chmod(mode); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}
